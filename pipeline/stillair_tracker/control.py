"""Earth paper-strip control (Plan B): turn the team's clip + hand-read mark crossings into
data/derived/control_result.json (contract control/1, docs/DATA_CONTRACTS.md section 8).

Usage (from pipeline/):
  python -m stillair_tracker.control CLIP.mp4 --px-per-mm 11.8 --crossings crossings.csv \
      --recorded-at 2026-11-14T23:30:00Z --camera "Sony a7 III, 4K 30p, manual" --rotate-k 1 \
      [--t-window 3 40] --repo ..
crossings.csv: two columns mark_mm,t_s (header row), read by frame-stepping the clip as the flame
front crosses each ruler mark (t_s = frame index / fps). px_per_mm comes from the ruler in the
same plane as the strip. The tracker never sees the hand times.
"""
from __future__ import annotations
import argparse, csv, json, os
import numpy as np
from .segment import fit_line
from .video import track_video, probe


def hand_rate(crossings: list[tuple[float, float]]) -> tuple[float, float]:
    """Slope of mark position vs crossing time, with Student-t 95% half-width (needs >= 3 marks)."""
    if len(crossings) < 3:
        raise SystemExit("need at least 3 hand crossings for a rate with an interval")
    mm = np.array([c[0] for c in crossings], float); ts = np.array([c[1] for c in crossings], float)
    m, _, ci = fit_line(ts, mm)
    return abs(m), ci


def build(clip, px_per_mm, crossings, recorded_at, camera, rotate_k=1, t_window=None, step=1, scale=2, notes=""):
    _, _, fps = probe(clip)
    hr, hci = hand_rate(crossings)
    tr = track_video(clip, px_per_mm, step=step, scale=scale, rotate_k=rotate_k,
                     t_window=tuple(t_window) if t_window else (min(c[1] for c in crossings), max(c[1] for c in crossings)))
    rate = abs(tr["rate_mm_s"])
    return {
        "contract": "control/1",
        "_note": "Written with AI assistance (Claude Code). Generated by pipeline/stillair_tracker/control.py; regenerate, don't edit.",
        "test_id": "CTRL-1",
        "clip": {"fps": round(fps, 3), "recorded_at": recorded_at, "camera": camera, "scale_px_per_mm": px_per_mm},
        "hand": {"crossings": [{"mark_mm": float(a), "t_s": float(b)} for a, b in crossings],
                 "rate_mm_s": round(hr, 4), "ci95_mm_s": round(hci, 4)},
        "tracker": {"rate_mm_s": round(rate, 4), "ci95_mm_s": round(tr["ci95_mm_s"], 4),
                    "threshold_spread_mm_s": round(tr["threshold_spread_mm_s"], 4), "n_frames": tr["n_frames"],
                    "t_start_s": round(tr["t_start_s"], 3), "t_end_s": round(tr["t_end_s"], 3)},
        "diff_pct": round(100 * (round(rate, 4) - round(hr, 4)) / round(hr, 4), 1),
        "notes": notes or "Downward-burning paper strip in still air, 1 g; hand crossings by frame-stepping; scale from a ruler in the strip's plane.",
    }


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("clip"); ap.add_argument("--px-per-mm", type=float, required=True)
    ap.add_argument("--crossings", required=True); ap.add_argument("--recorded-at", required=True)
    ap.add_argument("--camera", required=True); ap.add_argument("--rotate-k", type=int, default=1)
    ap.add_argument("--t-window", type=float, nargs=2); ap.add_argument("--step", type=int, default=1)
    ap.add_argument("--scale", type=int, default=2); ap.add_argument("--notes", default="")
    ap.add_argument("--repo", default=".."); ap.add_argument("--out")
    a = ap.parse_args(argv)
    with open(a.crossings, newline="", encoding="utf-8") as h:
        rows = [(float(r["mark_mm"]), float(r["t_s"])) for r in csv.DictReader(h)]
    res = build(a.clip, a.px_per_mm, rows, a.recorded_at, a.camera, a.rotate_k, a.t_window, a.step, a.scale, a.notes)
    out = a.out or os.path.join(a.repo, "data", "derived", "control_result.json")
    with open(out, "w", encoding="utf-8") as h:
        json.dump(res, h, indent=2)
    print(f"hand {res['hand']['rate_mm_s']} +/- {res['hand']['ci95_mm_s']} mm/s | tracker {res['tracker']['rate_mm_s']} "
          f"+/- {res['tracker']['ci95_mm_s']} | diff {res['diff_pct']}% -> {out}")


if __name__ == "__main__":
    main()
