// Written with AI assistance (Claude Code)
// Writes docs/research/materials_to_test_first.md from web/src/data/moongap.json.
// Every number in the doc comes from that file; nothing is typed by hand.
// Usage: node scripts/materials-to-test-first.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

const SRC = "web/src/data/moongap.json";
const OUT = "docs/research/materials_to_test_first.md";
const raw = readFileSync(SRC);
const mg = JSON.parse(raw);
const sha = createHash("sha256").update(raw).digest("hex");

// Figure numbers and NASA Test 1 status in air, from ICES-2025-392 p. 8 (figure captions and text).
const META = {
  pmma: { name: "PMMA (acrylic)", fig: "Fig. 7", test1: "fails" },
  p213: { name: "P-213 tape", fig: "Fig. 8", test1: "fails" },
  cotton_smolder: { name: "Cotton T-shirt (smolder)", fig: "Fig. 10", test1: "fails" },
  polycarbonate: { name: "Polycarbonate", fig: "Fig. 11", test1: "passes" },
  nomex_velcro: { name: "Nomex Velcro", fig: "Fig. 12", test1: "passes" },
};
const VERDICT = { above_zero: "above zero", below_zero: "below zero", includes_zero: "includes zero" };
const f1 = (v) => v.toFixed(1);
const signed = (v) => (v > 0 ? "+" : v < 0 ? "−" : "") + Math.abs(v).toFixed(2);

const base = mg.reference_lines.moon_base_o2;
const rows = mg.ranking.map((r) => {
  const m = mg.materials[r.material];
  const [lo, hi] = m.gap.ci95_pct;
  return {
    key: r.material, ...META[r.material],
    lunar: m.lunar.limit_pct, earth0: m.zero_flow.intercept_pct,
    gap: m.gap.gap_pct, lo, hi, width: hi - lo, verdict: m.gap.verdict,
    wstfMax: Math.max(...m.wstf_points.o2_pct), wstfMin: Math.min(...m.wstf_points.o2_pct),
  };
});
const by = (k) => rows.find((r) => r.key === k);
const thin = rows.filter((r) => r.verdict === "includes_zero").sort((a, b) => b.width - a.width);
const above = rows.filter((r) => r.verdict === "above_zero");
const below = rows.filter((r) => r.verdict === "below_zero");
const allWstfMax = Math.max(...rows.map((r) => r.wstfMax));
const allLunarMax = Math.max(...rows.map((r) => r.lunar));

const L = [];
L.push("<!-- Written with AI assistance (Claude Code) -->");
L.push("# Where NASA's lunar-gravity fire data are most surprising or thinnest");
L.push("");
L.push("This page complements [`suggestions_for_nasa.md`](suggestions_for_nasa.md). That page says **what to measure**; this one says **which materials the existing data leave most open**. It is an independent student team's reading of NASA's public data. NASA has not reviewed or endorsed it. **It is not a safety ranking**: no material here is called safe or unsafe.");
L.push("");
L.push(`Generated by \`scripts/materials-to-test-first.mjs\` from \`${SRC}\` (sha256 \`${sha}\`). Every number below is a field of that file: \`lunar.limit_pct\`, \`zero_flow.intercept_pct\`, \`gap.gap_pct\`, \`gap.ci95_pct\`, \`gap.verdict\` and \`wstf_points.o2_pct\`. Test 1 status and figure numbers are from ICES-2025-392 p. 8.`);
L.push("");
L.push("## The five materials");
L.push("");
L.push("Moon Gap = Earth still-air estimate minus lunar-gravity limit, in percentage points of oxygen. A positive gap means the lunar test kept burning on less oxygen than the Earth trend extended to zero flow.");
L.push("");
L.push("| Material | Figure | NASA Test 1 in air | Lunar-gravity limit (% O2) | Earth still-air estimate (% O2) | Moon Gap (95% range) | Range vs zero | Range width |");
L.push("|---|---|---|---|---|---|---|---|");
for (const r of rows) {
  const label = r.key === "pmma" || r.key === "p213" ? `${r.name} (as captioned)` : r.name;
  L.push(`| ${label} | ${r.fig} | ${r.test1} | ${f1(r.lunar)} | ${f1(r.earth0)} | ${signed(r.gap)} (${signed(r.lo)} to ${signed(r.hi)}) | ${VERDICT[r.verdict]} | ${r.width.toFixed(2)} |`);
}
L.push("");
const ex = mg.excluded.find((e) => e.material === "cotton_flaming");
L.push(`**Not ranked: cotton T-shirt (flaming), Fig. 9.** ${ex.reason}`);
L.push("");
L.push("**Figs. 7-9 caveat.** Fitted to their points, the image printed as Fig. 7 (captioned PMMA) matches Table 2's P-213 row, and Fig. 8 (captioned P-213) matches its Beefy-T flaming row; Fig. 9 repeats Fig. 10. The images may be shifted by one material (ICES-2025-392 pp. 8, 11; `moongap.json` caveats). We keep the captions' labels and do not pin the PMMA and P-213 rows on those materials.");
L.push("");
L.push("## Planned Moon-base air, side by side");
L.push("");
L.push(`The challenge page plans Moon-base air at "30% or greater" oxygen at "10.2 psi or less"; the ${f1(base.o2_pct)}% line below is \`reference_lines.moon_base_o2\`. The lunar tests ran at 8.2 psia, which ICES-2025-392 p. 6 calls the planned NASA lunar habitat pressure. The two are shown next to each other, not subtracted, because the pressures are not the same test condition.`);
L.push("");
L.push(`| Material | Lunar-gravity limit (% O2, 8.2 psia) | Planned base air (% O2) | Earth forced-flow limits, WSTF (% O2, 60-144 cm/s) |`);
L.push("|---|---|---|---|");
for (const r of rows) L.push(`| ${r.name}${r.key === "pmma" || r.key === "p213" ? " (as captioned)" : ""} | ${f1(r.lunar)} | ${f1(base.o2_pct)} | ${f1(r.wstfMin)} to ${f1(r.wstfMax)} |`);
L.push("");
L.push(`Every lunar-gravity limit (highest ${f1(allLunarMax)}%) is below the ${f1(base.o2_pct)}% line, and so is every Earth forced-flow limit for the same materials (highest ${f1(allWstfMax)}%). So this is a point about oxygen-rich air at both gravities, not something specific to the Moon.`);
L.push("");
L.push("## Three groups, and what would settle each");
L.push("");
L.push("### Most surprising");
for (const r of above) L.push(`- **The figure captioned ${r.name.replace(" tape", "")} (${r.fig})**: Moon Gap ${signed(r.gap)} points, range ${signed(r.lo)} to ${signed(r.hi)}, the only range entirely above zero. NASA itself reports, for Figs. 7-9, that the lunar-gravity limit was "less than the extrapolated value (for any assumed buoyant velocity) from the WSTF testing. This result is contrary to expected behavior" (ICES-2025-392 p. 9).`);
L.push("- **What would settle it:** first confirm which material that image shows (suggestions #5), then repeat it with one method difference changed at a time (suggestions #4, the matched-method lunar and WSTF repeats).");
L.push("");
L.push("### Thinnest evidence");
for (const r of thin) L.push(`- **${r.name}${r.key === "pmma" ? " (as captioned)" : ""} (${r.fig})**: Moon Gap ${signed(r.gap)}, range ${signed(r.lo)} to ${signed(r.hi)} (width ${r.width.toFixed(2)}), which includes zero, so the sign is not settled.`);
L.push("- **What would settle it:** more repeats near each limit and the same ignition method in both facilities (suggestions #4); the lunar limit's own test-step size is not in the 95% range, so finer oxygen steps would also help.");
L.push("");
L.push("### Moon easier than the Earth trend");
for (const r of below) L.push(`- **${r.name} (${r.fig})**: Moon Gap ${signed(r.gap)}, range ${signed(r.lo)} to ${signed(r.hi)}, entirely below zero: in lunar gravity it needed more oxygen than the Earth trend extended to zero flow.`);
L.push("- **What would settle why:** a measured flow at the flame in lunar gravity (suggestions #1), since the Earth estimate is an extrapolation to zero flow and the lunar flow is not known.");
L.push("");
L.push("## What NASA could test next (FM2 and beyond)");
L.push("");
L.push("In short: confirm the identity and repeat the most surprising result, tighten the three open ranges, and measure the flow at the flame. FM2's slides say its hardware \"does not support ignition approaches used at WSTF or in Centrifuge. (flow change, oxygen change)\" (PDF p. 14), so some of these need other facilities too.");
L.push("");
L.push("## Limits of this page");
L.push("");
L.push("- The lunar-gravity limits come from about 5-second drop-tower centrifuge runs (ICES-2025-392).");
L.push("- The Earth still-air estimate is a straight-line fit to 60-144 cm/s data extended to zero flow, far outside the tested range.");
L.push("- No airflow is stated for the Moon: NASA reports the velocity induced by the simulated gravity as not known (ICES-2025-392 pp. 8, 10).");
L.push("- The Figs. 7-9 shift above means the PMMA and P-213 rows may belong to other materials.");
L.push("- An independent student team's analysis of public data, not NASA's findings.");
L.push("");
writeFileSync(OUT, L.join("\n"));
console.log(`wrote ${OUT} (${rows.length} materials, source sha256 ${sha.slice(0, 12)})`);
