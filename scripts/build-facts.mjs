// Written with AI assistance (Claude Code)
// Build step of the proof layer: turns our data files and the seed facts into the fact index.
// Every number carries {file, row, column, sha256} (or paper, page, quote for seed facts).
// Writes two git-ignored files:
//   api/_facts.ts                 the index /api/ask gates answers against
//   web/src/generated/facts.json  the same index, for the UI's provenance drawer
// Mock files never go in. Run after `npm run build -w proof`.
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { FACT_FILES, checkSeedFacts, factsFromFile, factsFromSeed } from "../proof/dist/index.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SEED = "data/reference/seed_facts.json";

const facts = [];
const files = [];
for (const rel of FACT_FILES) {
  const abs = join(root, rel);
  if (!existsSync(abs)) continue;
  const buf = readFileSync(abs);
  const sha256 = createHash("sha256").update(buf).digest("hex");
  const got = factsFromFile(rel, buf.toString("utf8"), sha256);
  facts.push(...got);
  files.push({ file: rel, sha256, facts: got.length });
}

// Files the UI cites directly but that hold no headline facts (per-photo edge tracks): listed with
// their checksum so every number shown from them still carries {file, row, column, sha256}.
const EDGES = "data/derived/edges";
if (existsSync(join(root, EDGES)))
  for (const name of readdirSync(join(root, EDGES)).filter((n) => n.endsWith(".csv")).sort()) {
    const rel = `${EDGES}/${name}`;
    files.push({ file: rel, sha256: createHash("sha256").update(readFileSync(join(root, rel))).digest("hex"), facts: 0 });
  }

const seed = JSON.parse(readFileSync(join(root, SEED), "utf8"));
const problems = checkSeedFacts(seed);
if (problems.length) {
  console.error(`build-facts: ${SEED} has problems:\n  ${problems.join("\n  ")}`);
  process.exit(1);
}
facts.push(...factsFromSeed(seed.facts));
files.push({ file: SEED, sha256: createHash("sha256").update(readFileSync(join(root, SEED))).digest("hex"), facts: seed.facts.length });

const ids = new Set();
for (const f of facts) {
  if (ids.has(f.id)) {
    console.error(`build-facts: duplicate fact id ${f.id}`);
    process.exit(1);
  }
  ids.add(f.id);
}

const index = { generated_by: "scripts/build-facts.mjs", files, facts };
writeFileSync(
  join(root, "api/_facts.ts"),
  `// Generated by scripts/build-facts.mjs. Do not edit.\nimport type { Fact } from "@still-air/proof";\n\nexport const FACT_FILES_USED = ${JSON.stringify(files, null, 2)};\n\nexport const FACTS: Fact[] = ${JSON.stringify(facts)};\n`,
);
mkdirSync(join(root, "web/src/generated"), { recursive: true });
writeFileSync(join(root, "web/src/generated/facts.json"), JSON.stringify(index) + "\n");
console.log(`build-facts: ${facts.length} facts from ${files.length} files (${files.map((f) => `${f.file}: ${f.facts}`).join(", ")})`);
