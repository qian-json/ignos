// Written with AI assistance (Claude Code)
// Builds data/reference/psi_investigations.json (contract investigations/1) from the research
// catalog docs/research/psi_investigations.json (rubric: docs/research/psi_investigations_catalog.md).
// Keeps the fields the UI table and /api/ask need, drops the catalog's ranking (overall_rank,
// relevance_total, per-record relevance.basis: the UI ranks from the scores), sorts by PSI number,
// and refuses to write a file that fails validateInvestigations().
// Run after `npm run build -w proof`:  node scripts/build-investigations.mjs
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { INVESTIGATION_SETTINGS, validateInvestigations } from "../proof/dist/index.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = "docs/research/psi_investigations.json";
const RUBRIC = "docs/research/psi_investigations_catalog.md";
const OUT = "data/reference/psi_investigations.json";

const buf = readFileSync(join(root, SRC));
const source = JSON.parse(buf.toString("utf8"));
if (!Array.isArray(source)) throw new Error(`${SRC}: expected an array of investigations`);

function need(rec, key) {
  if (!(key in rec)) throw new Error(`${SRC}: ${rec.accession ?? "?"} has no ${key}`);
  return rec[key];
}
const pick = (rec, keys) => Object.fromEntries(keys.map((k) => [k, need(rec, k)]));
const psiNumber = (acc) => Number(acc.replace(/^PSI-/, ""));

const investigations = source
  .map((rec) => ({
    accession: need(rec, "accession"),
    // The catalog writes "" for the ground grants, which have no acronym; the contract uses null.
    acronym: need(rec, "acronym") === "" ? null : rec.acronym,
    ...pick(rec, [
      "full_name", "psi_doi", "psi_url", "investigation_type", "research_subarea",
      "fire_safety_theme",
    ]),
    years: pick(need(rec, "years"), ["psi_investigation_dates", "operations"]),
    ...pick(rec, ["platform", "hardware", "fuel_sample"]),
    atmosphere: pick(need(rec, "atmosphere"), ["o2", "pressure"]),
    ...pick(rec, ["flow", "gravity", "diagnostics"]),
    psi_data: pick(need(rec, "psi_data"), ["total_size_gb", "n_files", "file_types", "source"]),
    ...pick(rec, ["pi", "key_finding", "key_finding_source"]),
    key_papers: need(rec, "key_papers").map((p) => ({
      citation: need(p, "citation"),
      // The catalog writes "" for "no DOI"; the contract uses null.
      doi: need(p, "doi") === "" ? null : p.doi,
      doi_verified: need(p, "doi_verified"),
      ...("note" in p ? { note: p.note } : {}),
    })),
    relevance: Object.fromEntries(
      INVESTIGATION_SETTINGS.map((s) => {
        const cell = need(need(rec, "relevance"), s);
        return [s, { score: need(cell, "score"), why: need(cell, "why") }];
      }),
    ),
    notes_unverified: need(rec, "notes_unverified"),
  }))
  .sort((a, b) => psiNumber(a.accession) - psiNumber(b.accession));

const file = {
  contract: "investigations/1",
  _note:
    `Written with AI assistance (Claude Code). Generated by scripts/build-investigations.mjs from ${SRC}; ` +
    "never edit by hand. Sorted by PSI accession number, not by relevance.",
  relevance_note:
    "Relevance scores (whole numbers 1 to 5, one per crew setting) are the Still Air team's judgment, not NASA's: " +
    `they follow the rubric in ${RUBRIC}, were assigned with AI assistance, and have not been reviewed by a ` +
    "subject-matter expert. Key findings are quoted from the source named next to each one.",
  derived_from: {
    file: SRC,
    sha256: createHash("sha256").update(buf).digest("hex"),
    generated_by: "scripts/build-investigations.mjs",
    rubric: RUBRIC,
  },
  investigations,
};

const res = validateInvestigations(file);
if (!res.ok) {
  console.error(`build-investigations: the output fails investigations/1, nothing written:`);
  for (const i of res.issues.slice(0, 50)) console.error(`  ${i.path}: ${i.message}`);
  process.exit(1);
}
writeFileSync(join(root, OUT), `${JSON.stringify(file, null, 2)}\n`);
console.log(`build-investigations: wrote ${OUT} (${investigations.length} investigations, source sha256 ${file.derived_from.sha256.slice(0, 12)}…)`);
