"""Extracts the text of every page of the source PDFs for the /api/ask index.

Writes scripts/ask-index/pdf_pages.json: [{ paper, file, page, text }], page 1-based (the slide
number for the LPSC deck). Needs pdftotext (poppler). Run from the repo root:
    python3 -I scripts/ask-index/extract_pdf_pages.py
Re-run when a file in docs/sources/ changes; scripts/build-ask-index.mjs reads the output.
"""
import hashlib
import json
import re
import subprocess
from pathlib import Path

SOURCES = [
    ("ices2025", "docs/sources/ICES_2025-392-correctedcaptions.pdf"),
    ("link2018_si", "docs/sources/Link2018_SciRep_SI.pdf"),
    ("fm2_2026", "docs/sources/Ferkul_LPSC_2026_v2.pdf"),
]


def page_count(path: str) -> int:
    info = subprocess.run(["pdfinfo", path], capture_output=True, text=True, check=True).stdout
    return int(re.search(r"^Pages:\s+(\d+)", info, re.M).group(1))


def page_text(path: str, page: int) -> str:
    out = subprocess.run(
        ["pdftotext", "-enc", "UTF-8", "-f", str(page), "-l", str(page), path, "-"],
        capture_output=True, text=True, check=True,
    ).stdout
    return re.sub(r"[ \t]+", " ", out.replace("\f", "")).strip()


def main() -> None:
    pages, files = [], []
    for paper, path in SOURCES:
        if not Path(path).exists():
            # e.g. the public code export leaves out ICES-2025-392 (its NTRS record says it may include
            # copyrighted material); scripts/build-ask-index.mjs then skips that paper's passages.
            print(f"skipped {paper}: {path} not found")
            continue
        files.append({"paper": paper, "file": path, "sha256": hashlib.sha256(Path(path).read_bytes()).hexdigest()})
        for n in range(1, page_count(path) + 1):
            text = page_text(path, n)
            if text:
                pages.append({"paper": paper, "file": path, "page": n, "text": text})
    out = {"_note": "Generated by scripts/ask-index/extract_pdf_pages.py from docs/sources/. Do not edit.", "files": files, "pages": pages}
    Path("scripts/ask-index/pdf_pages.json").write_text(json.dumps(out, ensure_ascii=False, indent=1) + "\n")
    print(f"{len(pages)} pages from {len(files)} PDFs")


if __name__ == "__main__":
    main()
