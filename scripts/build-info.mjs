// Writes api/_build-info.ts with the git commit and the data files present at build time.
// Runs before build and test. The output is git-ignored.
import { execSync } from "node:child_process";
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

function resolveCommit() {
  if (process.env.VERCEL_GIT_COMMIT_SHA) return process.env.VERCEL_GIT_COMMIT_SHA;
  try {
    return execSync("git rev-parse HEAD", { cwd: root, stdio: ["ignore", "pipe", "ignore"] })
      .toString()
      .trim();
  } catch {
    return "unknown";
  }
}

function listFiles(dir) {
  let out = [];
  let entries;
  try {
    entries = readdirSync(dir);
  } catch {
    return out;
  }
  for (const name of entries) {
    if (name === ".gitkeep" || name === ".DS_Store") continue;
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out = out.concat(listFiles(full));
    else out.push(relative(root, full).split("\\").join("/"));
  }
  return out;
}

const dataFiles = listFiles(join(root, "data"))
  .filter((f) => f !== "data/README.md")
  // data tables only: /api/health is public, and archives and notes can carry names
  .filter((f) => /\.(csv|json)$/.test(f))
  .sort();
const info = { commit: resolveCommit(), dataFiles };

writeFileSync(
  join(root, "api", "_build-info.ts"),
  `// Generated by scripts/build-info.mjs. Do not edit.\nexport const buildInfo: { commit: string; dataFiles: string[] } = ${JSON.stringify(info, null, 2)};\n`,
);
console.log(`build-info: commit ${info.commit.slice(0, 7)}, ${dataFiles.length} data file(s)`);
