export type Row = Record<string, string> & { _row: number };

const SHA = new Map<string, string>((factsIndex as { files: { file: string; sha256: string }[] }).files.map((f) => [f.file, f.sha256]));
export const FACTS = (factsIndex as { facts: Fact[] }).facts;
export const FACT_FILES = (factsIndex as { files: { file: string; sha256: string; facts: number }[] }).files;

function table(text: string): Row[] {
  const p = parseCsv(text.replace(/\r\n/g, "\n"));
  return p.records.map((rec, i) => {
    const r = { _row: i } as Row;
    p.header.forEach((h, k) => (r[h] = rec.cells[k] ?? ""));
    return r;
  });
}

/** Provenance for one cell of a data file. */
export function cell(file: string, row: number, column: string): NumberSource {
  return { file, row, column, sha256: SHA.get(file) ?? "" };
}

