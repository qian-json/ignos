/** A row's confidence, from the notes column. */
export const lowConfidence = (r: Row) => /LOW CONFIDENCE/i.test(r.notes ?? "");

/**
 * The validation rule from pipeline/METHOD.md, shared with the proof layer so the page and /api/ask
 * count the same steps: only low-flow steps (under 1 cm/s) that the tracker didn't flag. Early
 * high-flow steps share an ignition-transient bias even when their interval is tight.
 */
export const validated = (r: Row) => isValidatedStep(r);

/** Median of a list (for summary figures computed from the rows on screen). */
export function median(xs: number[]): number {
  const s = [...xs].sort((a, b) => a - b);
  const m = s.length >> 1;
  return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2;
}

